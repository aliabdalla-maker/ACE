/**
 * Helper to translate a string into the selected target language.
 * Falls back gracefully to English or target language dictionary lookups.
 */
export function getTranslation(key: string, targetLangCode: string, defaultText?: string): string {
  const dictionaryItem = TRANSLATIONS[key];
  if (dictionaryItem && dictionaryItem[targetLangCode]) {
    return dictionaryItem[targetLangCode];
  }
  // Try English fallback from dictionary
  if (dictionaryItem && dictionaryItem['en']) {
    return dictionaryItem['en'];
  }
  return defaultText || key;
}
